// ui/src/ui2/i18n/locales.ts
//
// myrmidon(UI2): locale catalogs for the ui2 tree only. The vendor i18n
// bundle ships 40 locale files with a 6-key catalog; ui2 needs exactly two
// locales (en is the source, ru is the product requirement) and a flat
// key space that a test can walk exhaustively. Keys live here, not in the
// vendor `ui/src/i18n/locales/*.json` files, so the two catalogs never
// entangle: the vendor parity test (locale-validation) walks its own files
// and stays untouched.
//
// Rules pinned by ui2.i18n.myrmidon.test.ts:
//   - every en key has a ru key and vice versa (structural parity);
//   - interpolation placeholders match between en and ru;
//   - no ui2 component renders a hard-coded user-visible literal (the
//     no-English-in-RU rule is enforced at the key level: components take
//     strings from the catalog only).

